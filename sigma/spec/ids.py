"""Frozen numeric identifiers for the Sigma v2 wire format."""

from enum import IntEnum

CONTEXT_MAGIC = b"SIGMACTX"
CONTEXT_VERSION = 2
DIGEST_MAGIC = b"SIGMADG2\x00"
EVIDENCE_MAGIC = b"SIGMAAE"
EVIDENCE_VERSION = 2


class SuiteId(IntEnum):
    REFERENCE_STREAM_WIDE_V2_2 = 0x0101
    LIGHTWEIGHT_STREAM_WIDE_V2_2 = 0x0102
    SIMULTANEOUS_TREE_WIDE_V2_2 = 0x0103
    PARANOID_CROSS_WIDE_V2_2 = 0x0104
    PARANOID_DEEP_V2_2 = 0x0105
    PARANOID_DEEP_VECTOR_V2_2 = 0x0106


class EvidenceType(IntEnum):
    WIDE_ROOTS = 0x0001
    CROSS_WIDE = 0x0002


class SignatureAlgorithmId(IntEnum):
    ED25519 = 0x0001


class AlgorithmId(IntEnum):
    SHA512 = 0x0001
    SHA3_512 = 0x0002
    BLAKE2B_512 = 0x0003
    SHAKE256_512 = 0x0004


class AnchorProfileId(IntEnum):
    STREAM_WIDE = 0x0001
    TREE_WIDE = 0x0002
    CROSS_WIDE = 0x0003


class RoundProfileId(IntEnum):
    WIDE_ONCE = 0x0001
    DEEP = 0x0002
    DEEP_VECTOR = 0x0003


class OutputProfileId(IntEnum):
    MULTI_STATE = 0x0001


class ContextFieldId(IntEnum):
    SUITE = 0x0001
    ANCHOR_PROFILE = 0x0002
    ROUND_PROFILE = 0x0003
    OUTPUT_PROFILE = 0x0004
    TARGET_ROUND = 0x0005
    STATE_COUNT = 0x0006
    BRANCHES = 0x0007
    CHUNK_SIZE = 0x0008
    SALT = 0x0009
    CHALLENGE = 0x000A
    APPLICATION_CONTEXT = 0x000B


class DomainId(IntEnum):
    BRANCH = 0x0001
    BRANCH_END = 0x0002
    ANCHOR_EVIDENCE = 0x0003
    INIT = 0x0004
    ROUND = 0x0005
    CROSS = 0x0006
    DEEP = 0x0007
    FOLD = 0x0008
    OUTPUT = 0x0009
    TREE_LEAF = 0x000A
    TREE_NODE = 0x000B
    TREE_EMPTY = 0x000C
    SIGNED_COMMITMENT = 0x000D
    VECTOR_INIT = 0x000E
    VECTOR_ROUND = 0x000F
